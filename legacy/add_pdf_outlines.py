#!/usr/bin/env python3
"""
Скрипт для додавання ієрархічного змісту (Document Outline / Bookmarks)
до PDF-файлів практичних занять з дослідження операцій.

Вимоги:
- Тільки рівні # (L1), ## (L2), ### (L3)
- Жодних нумерованих списків як окремих розділів
- Автоматичне розгортання панелі закладок у PDF-рідері (/UseOutlines)
- Повне збереження вихідного тексту, векторних формул та графіків
"""

import sys
import os
import pypdf


def apply_outline(input_path: str, output_path: str, outline_tree: list) -> None:
    """
    Зчитує вхідний PDF, переносить усі його сторінки та додає дерево закладок.
    
    :param input_path: шлях до вихідного PDF
    :param output_path: шлях для збереження обробленого PDF
    :param outline_tree: список словників формату:
           {"title": "Назва", "page": <номер сторінки з 0>, "children": [...]}
    """
    if not os.path.exists(input_path):
        print(f"Помилка: файл не знайдено -> {input_path}")
        return

    reader = pypdf.PdfReader(input_path)
    writer = pypdf.PdfWriter()

    # Переносимо сторінки 1-в-1 без спотворень
    for page in reader.pages:
        writer.add_page(page)

    # Рекурсивне створення багаторівневого Outline
    def add_nodes(nodes, parent=None):
        for node in nodes:
            item = writer.add_outline_item(
                title=node["title"],
                page_number=node["page"],
                parent=parent
            )
            if "children" in node and node["children"]:
                add_nodes(node["children"], parent=item)

    add_nodes(outline_tree)

    # Задаємо директиву для переглядача відкривати панель закладок одразу
    writer.page_mode = "/UseOutlines"

    with open(output_path, "wb") as f_out:
        writer.write(f_out)

    print(f"✓ Успішно створено: {output_path} ({len(reader.pages)} стор.)")


